public class ifelse1 {
    public static void main (String[] args){
        int marks = 60;
        if (marks >=90){
            System.out.println("A GRADE");
        }
        else if (marks>75){
            System.out.println("B GRADE");
        }
        else{
            System.out.println("C GRADE");
        }
    }
}
